// 포지션별 점수 폭 → 라인갭 가중치 (폭 큰 포지션 = 갭이 더 치명적)
// 탑/정글/원딜 저티어=압살(폭 큼), 서폿=성비 좋음(폭 작음)
export function laneWeights(table = TABLE) {
  const rows = Object.values(table);
  const span = POS.map((_, i) => {
    const col = rows.map((r) => r[i]);
    return Math.max(...col) - Math.min(...col);
  });
  const mx = Math.max(...span) || 1;
  return span.map((s) => s / mx);
}
